require "yaml"
require "tmpdir"
require "fileutils"
require "open3"

CODEGEN_DIR = File.expand_path("..", __dir__)
GENERATE_SCRIPT = File.join(CODEGEN_DIR, "generate.rb")
FIXTURES_DIR = File.join(__dir__, "fixtures")
ROOT = File.expand_path("../../", CODEGEN_DIR)

require_relative "../schema"

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def valid_yaml_raw
  YAML.safe_load_file(File.join(FIXTURES_DIR, "valid_agents.yaml"))
end

def run_generate(*args, env: {})
  cmd = ["ruby", GENERATE_SCRIPT, *args]
  out, err, status = Open3.capture3(env, *cmd, chdir: ROOT)
  [out, err, status]
end

# ---------------------------------------------------------------------------
# Schema validation
# ---------------------------------------------------------------------------

RSpec.describe Schema do
  describe ".validate!" do
    it "accepts a valid config" do
      expect { Schema.validate!(valid_yaml_raw) }.not_to raise_error
    end

    it "raises on missing schema_version" do
      raw = valid_yaml_raw.tap { |r| r.delete("schema_version") }
      expect { Schema.validate!(raw) }.to raise_error(Schema::Error, /schema_version/)
    end

    it "raises on missing field_keys" do
      raw = valid_yaml_raw.tap { |r| r.delete("field_keys") }
      expect { Schema.validate!(raw) }.to raise_error(Schema::Error, /field_keys/)
    end

    it "raises on missing metric_slugs" do
      raw = valid_yaml_raw.tap { |r| r.delete("metric_slugs") }
      expect { Schema.validate!(raw) }.to raise_error(Schema::Error, /metric_slugs/)
    end

    it "raises on missing agents" do
      raw = valid_yaml_raw.tap { |r| r.delete("agents") }
      expect { Schema.validate!(raw) }.to raise_error(Schema::Error, /agents/)
    end

    it "raises on empty agents hash" do
      raw = valid_yaml_raw
      raw["agents"] = {}
      expect { Schema.validate!(raw) }.to raise_error(Schema::Error, /empty/)
    end

    it "raises on agent id with invalid pattern" do
      raw = valid_yaml_raw
      meta = raw["agents"].values.first.dup
      raw["agents"] = { "BadAgent" => meta }
      expect { Schema.validate!(raw) }.to raise_error(Schema::Error, /lowercase snake_case/)
    end

    it "raises on invalid color format" do
      raw = valid_yaml_raw
      raw["agents"]["claude_code"]["color"] = "red"
      expect { Schema.validate!(raw) }.to raise_error(Schema::Error, /color/)
    end

    it "raises on empty hook_scopes" do
      raw = valid_yaml_raw
      raw["agents"]["claude_code"]["hook_scopes"] = []
      expect { Schema.validate!(raw) }.to raise_error(Schema::Error, /hook_scopes/)
    end

    it "raises on unknown hook_scope value" do
      raw = valid_yaml_raw
      raw["agents"]["claude_code"]["hook_scopes"] = ["global"]
      expect { Schema.validate!(raw) }.to raise_error(Schema::Error, /hook_scopes/)
    end

    it "raises on missing field key" do
      raw = valid_yaml_raw
      raw["agents"]["claude_code"]["fields"].delete("input_tokens")
      expect { Schema.validate!(raw) }.to raise_error(Schema::Error, /missing keys/)
    end

    it "raises on unknown field key" do
      raw = valid_yaml_raw
      raw["agents"]["claude_code"]["fields"]["unknown_field"] = true
      expect { Schema.validate!(raw) }.to raise_error(Schema::Error, /unknown keys/)
    end

    it "raises on missing metric slug" do
      raw = valid_yaml_raw
      raw["agents"]["claude_code"]["metrics"].delete("iteration-depth")
      expect { Schema.validate!(raw) }.to raise_error(Schema::Error, /missing slugs/)
    end

    it "raises on unknown metric slug" do
      raw = valid_yaml_raw
      raw["agents"]["claude_code"]["metrics"]["nonexistent-metric"] = true
      expect { Schema.validate!(raw) }.to raise_error(Schema::Error, /unknown slugs/)
    end

    it "raises on non-boolean field value" do
      raw = valid_yaml_raw
      raw["agents"]["claude_code"]["fields"]["input_tokens"] = "yes"
      expect { Schema.validate!(raw) }.to raise_error(Schema::Error, /true or false/)
    end
  end
end

