RSpec.describe "generate.rb golden-file rendering" do
  let(:generated_go) { File.read(File.join(ROOT, "cli/internal/agents/registry.gen.go")) }
  let(:generated_rb) { File.read(File.join(ROOT, "server/app/models/agent_registry.rb")) }
  let(:generated_ts) { File.read(File.join(ROOT, "dashboard/src/lib/agents.gen.ts")) }
  let(:generated_txt) { File.read(File.join(ROOT, "server/db/agent_types.txt")) }

  it "generates Go file with correct header" do
    expect(generated_go).to start_with("// Code generated by scripts/codegen-agents — DO NOT EDIT.")
  end

  it "generates Go file with AgentID type" do
    expect(generated_go).to include("type AgentID string")
  end

  it "generates Go consts for each agent" do
    expect(generated_go).to include('ClaudeCode AgentID = "claude_code"')
  end

  it "generates Go Registry() function" do
    expect(generated_go).to include("func Registry() map[AgentID]Metadata {")
  end

  it "generates Ruby file with correct header" do
    expect(generated_rb).to start_with("# Code generated by scripts/codegen-agents — DO NOT EDIT.")
  end

  it "generates Ruby VALID_IDS constant" do
    expect(generated_rb).to include("VALID_IDS = AGENTS.keys.freeze")
  end

  it "generates Ruby supports_field? method" do
    expect(generated_rb).to include("def self.supports_field?(id, field)")
  end

  it "generates TypeScript file with correct header" do
    expect(generated_ts).to start_with("// Code generated by scripts/codegen-agents — DO NOT EDIT.")
  end

  it "generates TypeScript AgentType union" do
    expect(generated_ts).to include('export type AgentType = "claude_code" | "copilot_cli"')
  end

  it "generates TypeScript ALL_AGENTS constant" do
    expect(generated_ts).to include("export const ALL_AGENTS: readonly AgentType[]")
  end

  it "generates TypeScript isAgentType function" do
    expect(generated_ts).to include("export function isAgentType(value: string): value is AgentType")
  end

  it "generates agent_types.txt with one agent per line" do
    lines = generated_txt.lines.map(&:chomp).reject(&:empty?)
    expect(lines).to eq(["claude_code", "copilot_cli"])
  end

  it "generates Ruby file that parses without syntax error" do
    _, err, status = Open3.capture3("ruby", "-c", File.join(ROOT, "server/app/models/agent_registry.rb"))
    expect(status.success?).to be(true), "ruby -c failed: #{err}"
  end
end

# ---------------------------------------------------------------------------
# --check mode
# ---------------------------------------------------------------------------

RSpec.describe "generate.rb --check mode" do
  it "exits 0 when generated files are in sync" do
    _, err, status = run_generate("--check")
    expect(status.exitstatus).to eq(0), "expected exit 0 but got #{status.exitstatus}: #{err}"
  end

  it "exits 1 and reports drift when a generated file is stale" do
    Dir.mktmpdir do |tmpdir|
      # Copy root to a temp location and corrupt one generated file
      fake_root = File.join(tmpdir, "ax")
      FileUtils.cp_r(ROOT, fake_root)

      go_file = File.join(fake_root, "cli/internal/agents/registry.gen.go")
      File.write(go_file, "// stale content\n")

      _, err, status = Open3.capture3(
        "ruby", File.join(fake_root, "scripts/codegen-agents/generate.rb"), "--check",
        chdir: fake_root
      )
      expect(status.exitstatus).to eq(1), "expected exit 1 but got #{status.exitstatus}"
      expect(err).to include("cli/internal/agents/registry.gen.go")
    end
  end
end
